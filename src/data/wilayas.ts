/**
 * Calculates distance between two GPS coordinates in Kilometers (Haversine formula)
 */
export function calculateDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Radius of Earth in KM
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const distance = R * c;
  return Math.max(0.5, Math.round(distance * 10) / 10);
}

/**
 * Dynamic Pricing Engine:
 * Base fare: 250 DZD (covers pickup + first 1.5 km)
 * Additional per-km rate: 60 DZD/km
 * Rounded to nearest 50 DZD
 */
export function calculateSuggestedFare(distanceKm: number): number {
  const baseFare = 250;
  const perKmRate = 60;
  const extraDistance = Math.max(0, distanceKm - 1.5);
  const rawFare = baseFare + extraDistance * perKmRate;
  return Math.round(rawFare / 50) * 50;
}
